// Isolated WASM PostgreSQL only. No connection URL or remote database path.
import { PGlite } from "@electric-sql/pglite";
import { pgcrypto } from "@electric-sql/pglite/contrib/pgcrypto";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { format } from "prettier";
const db = new PGlite({ extensions: { pgcrypto } });
await db.exec(`CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role BYPASSRLS;
CREATE SCHEMA supabase_migrations; CREATE TABLE supabase_migrations.schema_migrations(version text PRIMARY KEY,name text,statements text[]); CREATE SCHEMA auth; CREATE TABLE auth.users(id uuid PRIMARY KEY);
CREATE SCHEMA extensions; CREATE EXTENSION pgcrypto WITH SCHEMA extensions;
CREATE SCHEMA cron; CREATE TABLE cron.job(jobid bigint,jobname text); CREATE SCHEMA net; CREATE SCHEMA vault;
CREATE TABLE vault.secrets(id uuid,name text); CREATE TABLE vault.decrypted_secrets(id uuid,name text,decrypted_secret text);`);
const root = process.cwd();
for (const file of readdirSync(root + "/supabase/migrations").sort()) {
  let sql = readFileSync(root + "/supabase/migrations/" + file, "utf8").replace(
    /CREATE EXTENSION IF NOT EXISTS pg_(cron|net);/g,
    "",
  );
  try {
    await db.exec(sql);
  } catch (e) {
    console.log("FAIL", file, e.message);
    process.exit(1);
  }
}

const columns = (
  await db.query(
    `SELECT table_name,column_name,data_type,udt_name,is_nullable,column_default FROM information_schema.columns WHERE table_schema='public' ORDER BY table_name,ordinal_position`,
  )
).rows;
const tables = [
  "lead_intakes",
  "lead_intake_sessions",
  "lead_intake_welcome_jobs",
  "lead_plan_completed_runs",
];
const rows = tables
  .map((table) => {
    const fields = columns
      .filter((c) => c.table_name === table)
      .map((c) => {
        const type =
          c.data_type === "boolean"
            ? "boolean"
            : /integer|numeric|double|real/.test(c.data_type)
              ? "number"
              : c.data_type === "jsonb"
                ? "unknown"
                : "string";
        return `    ${c.column_name}: ${type}${c.is_nullable === "YES" ? " | null" : ""};`;
      })
      .join("\n");
    return `  ${table}: {\n${fields}\n  };`;
  })
  .join("\n");
const generated = await format(
  `// Generated by bun run signup:db:types from an isolated migration replay.\nexport type SignupRecoveryRows = {\n${rows}\n};\n`,
  { parser: "typescript", tabWidth: 2 },
);
const typeFile = root + "/src/integrations/supabase/signup-recovery.types.ts";
if (process.argv.includes("--types")) writeFileSync(typeFile, generated);
else if (readFileSync(typeFile, "utf8") !== generated)
  throw new Error("Signup recovery types differ from the replayed schema");
try {
  await db.exec(readFileSync(root + "/supabase/signup-recovery.acceptance.sql", "utf8"));
} catch (error) {
  console.error("Signup behavioral check failed:", error.message, error.where ?? "");
  await db.close();
  process.exit(1);
}
const unsafe = (
  await db.query(`SELECT p.proname FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace
 WHERE n.nspname='public' AND ((p.proname LIKE '%signup%' AND p.proname <> 'apply_signup_consent_state') OR p.proname='resolve_signup_intake' OR p.proname='enqueue_lead_intake_welcome')
 AND (NOT p.prosecdef OR NOT ('search_path=public'=ANY(p.proconfig)) OR has_function_privilege('anon',p.oid,'EXECUTE') OR has_function_privilege('authenticated',p.oid,'EXECUTE'))`)
).rows;
if (unsafe.length) throw new Error("Unsafe database capability: " + JSON.stringify(unsafe));
console.log(
  "Signup recovery: full application migration replay, behavioral acceptance, types, and RPC security checks passed.",
);
console.log(
  "Local harness supplies Supabase roles/auth/ledger and inert extension schemas; pg_cron and pg_net installation is skipped. No external database or provider is contacted.",
);
await db.close();
